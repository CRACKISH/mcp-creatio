#!/usr/bin/env node
// Regenerates src/creatio/temporal/windows-zones.data.ts from the Unicode CLDR mapping of Windows
// time-zone ids to IANA zones (the "001" = default territory row of each Windows zone). Creatio
// stores a user's zone as a Windows id (`SysAdminUnit.TimeZoneId`, e.g. "FLE Standard Time"); Node
// only knows IANA names, so this table is what lets the server apply the zone's daylight-saving rules.
//
//   node scripts/generate-windows-zones.mjs [path-or-url-to-windowsZones.xml]
//
// Run it when CLDR adds or renames a Windows zone; review the diff and commit the generated file.
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const DEFAULT_SOURCE =
	'https://raw.githubusercontent.com/unicode-org/cldr/main/common/supplemental/windowsZones.xml';
const TARGET = fileURLToPath(
	new URL('../src/creatio/temporal/windows-zones.data.ts', import.meta.url),
);

async function load(source) {
	if (/^https?:\/\//.test(source)) {
		const response = await fetch(source);
		if (!response.ok) {
			throw new Error(`download failed: ${response.status} ${source}`);
		}
		return response.text();
	}
	return readFile(source, 'utf8');
}

const source = process.argv[2] ?? DEFAULT_SOURCE;
const xml = await load(source);
const rows = [...xml.matchAll(/<mapZone other="([^"]+)" territory="001" type="([^"]+)"\s*\/>/g)]
	.map(([, windows, iana]) => [windows, iana])
	.sort(([a], [b]) => a.localeCompare(b));
if (rows.length < 100) {
	throw new Error(`unexpected CLDR content: only ${rows.length} default mappings in ${source}`);
}
for (const [, iana] of rows) {
	new Intl.DateTimeFormat('en-US', { timeZone: iana }); // throws on a zone this Node cannot use
}

const quote = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const body = rows.map(([w, i]) => `\t[${quote(w)}, ${quote(i)}],`).join('\n');
await writeFile(
	TARGET,
	`// GENERATED by scripts/generate-windows-zones.mjs — do not edit by hand.
// Source: Unicode CLDR common/supplemental/windowsZones.xml (default territory "001").
// Copyright © 1991-2013 Unicode, Inc. CLDR data is licensed under the Unicode License
// (https://www.unicode.org/license.txt).

/** Windows time-zone id → IANA zone, one row per Windows zone. */
export const WINDOWS_TO_IANA: ReadonlyMap<string, string> = new Map([
${body}
]);
`,
);
console.log(`wrote ${rows.length} mappings to ${TARGET}`);
